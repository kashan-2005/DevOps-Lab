"""Write frontend/src/app/feature-schema.ts from the saved model bundle.

Keeps the Angular form in sync with the model. Re-run after retraining:
    python backend/export_frontend_schema.py
"""
from pathlib import Path
import json

import joblib
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
bundle = joblib.load(ROOT / "backend/models/model_bundle.joblib")
schema = bundle["schema"]
sample = pd.read_csv(ROOT / "data/sample_inputs.csv", nrows=1).iloc[0]

# name -> (label, unit, group)
META = {
    "age": ("Age", "years", "About you"),
    "gender": ("Gender", "", "About you"),
    "education_level": ("Education", "", "About you"),
    "job_type": ("Job sector", "", "About you"),
    "occupation": ("Occupation", "", "About you"),
    "income": ("Monthly income", "USD", "About you"),
    "insurance": ("Health insurance", "", "About you"),
    "healthcare_access": ("Access to healthcare", "", "About you"),
    "family_history": ("Family history of disease", "", "About you"),
    "bmi": ("Body mass index", "kg/m²", "Body and vitals"),
    "waist_size": ("Waist size", "cm", "Body and vitals"),
    "blood_pressure": ("Systolic blood pressure", "mmHg", "Body and vitals"),
    "heart_rate": ("Resting heart rate", "bpm", "Body and vitals"),
    "cholesterol": ("Total cholesterol", "mg/dL", "Body and vitals"),
    "glucose": ("Glucose", "mg/dL", "Body and vitals"),
    "insulin": ("Insulin", "µU/mL", "Body and vitals"),
    "physical_activity": ("Physical activity", "hours/week", "Daily habits"),
    "daily_steps": ("Daily steps", "steps", "Daily habits"),
    "exercise_type": ("Exercise type", "", "Daily habits"),
    "sleep_hours": ("Sleep", "hours/night", "Daily habits"),
    "sleep_quality": ("Sleep quality", "", "Daily habits"),
    "work_hours": ("Work", "hours/day", "Daily habits"),
    "screen_time": ("Screen time", "hours/day", "Daily habits"),
    "device_usage": ("Device usage", "", "Daily habits"),
    "sunlight_exposure": ("Sunlight exposure", "", "Daily habits"),
    "pet_owner": ("Owns a pet", "", "Daily habits"),
    "diet_type": ("Diet", "", "Food and drink"),
    "meals_per_day": ("Meals per day", "", "Food and drink"),
    "calorie_intake": ("Calories", "kcal/day", "Food and drink"),
    "sugar_intake": ("Sugar", "g/day", "Food and drink"),
    "water_intake": ("Water", "litres/day", "Food and drink"),
    "caffeine_intake": ("Caffeine", "", "Food and drink"),
    "alcohol_consumption": ("Alcohol", "", "Food and drink"),
    "smoking_level": ("Smoking", "", "Food and drink"),
    "stress_level": ("Stress level", "", "Mind"),
    "mental_health_score": ("Mental health score", "", "Mind"),
    "mental_health_support": ("Receives mental health support", "", "Mind"),
}
GROUPS = ["About you", "Body and vitals", "Daily habits", "Food and drink", "Mind"]

fields = []
for group in GROUPS:
    for name, (label, unit, g) in META.items():
        if g != group:
            continue
        rule = schema[name]
        item = {"name": name, "label": label, "unit": unit, "group": group,
                "kind": rule["kind"]}
        value = sample[name]
        if rule["kind"] == "number":
            item.update(min=rule["min"], max=rule["max"],
                        step=1 if rule["integer"] else "any",
                        sample=float(value))
        else:
            item.update(options=rule["options"], sample=str(value))
        fields.append(item)

assert {f["name"] for f in fields} == set(bundle["features"]), "META must cover every feature"

ts = f"""// AUTO-GENERATED by backend/export_frontend_schema.py from model_bundle.joblib.
// Do not edit by hand: retrain, then re-run the script.

export type Feature = {{
  name: string;
  label: string;
  unit: string;
  group: string;
  kind: 'number' | 'category';
  min?: number;
  max?: number;
  step?: number | 'any';
  options?: string[];
  sample: number | string;
}};

export const GROUPS: string[] = {json.dumps(GROUPS)};

export const FEATURES: Feature[] = {json.dumps(fields, indent=2, ensure_ascii=False)};
"""
out = ROOT / "frontend/src/app/feature-schema.ts"
out.write_text(ts, encoding="utf-8")
print(f"Wrote {out} with {len(fields)} fields")
